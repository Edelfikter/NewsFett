export const MASK_COLS = 72;
export const MASK_ROWS = 36;

/** Returns true if (lon, lat) falls on a land cell of the mask. */
export function isLand(lon: number, lat: number): boolean {
  const c = Math.floor((lon + 180) / (360 / MASK_COLS));
  const r = Math.floor((90 - lat) / (180 / MASK_ROWS));
  if (r < 0 || r >= MASK_ROWS || c < 0 || c >= MASK_COLS) return false;
  return WORLD_MASK[r][c] === '1';
}

/**
 * Convert geographic coordinates to equirectangular screen fractions.
 * Returns [x_fraction, y_fraction] both in [0, 1].
 */
export function geoToFraction(lon: number, lat: number): [number, number] {
  return [(lon + 180) / 360, (90 - lat) / 180];
}
